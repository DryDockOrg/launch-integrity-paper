/**
 * Compiles lib/integrity/sim/*.sol with the pinned solc-js and writes lib/integrity/sim/artifacts.ts
 * (ABI and runtime bytecode). The output is committed so the site and the Worker never need a compiler;
 * re-running this script must reproduce it byte for byte.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import solc from "solc";

const dir = join(process.cwd(), "lib/integrity/sim");
const files = ["Simulator.sol", "ForecastLedger.sol"];
const input = {
  language: "Solidity",
  sources: Object.fromEntries(files.map((file) => [file, { content: readFileSync(join(dir, file), "utf8") }])),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "cancun",
    metadata: { bytecodeHash: "none" },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((error: { severity: string }) => error.severity === "error");
if (errors.length) { for (const error of errors) console.error(error.formattedMessage); process.exit(1); }
const pick = (file: string, name: string) => output.contracts[file][name];
const sim = pick("Simulator.sol", "Simulator");
const ledger = pick("ForecastLedger.sol", "ForecastLedger");
const out = `// Generated by scripts/compile-simulator.ts with solc ${solc.version()}. Do not edit.
export const SIMULATOR_ABI = ${JSON.stringify(sim.abi)} as const;
export const SIMULATOR_CODE = "0x${sim.evm.deployedBytecode.object}" as const;
export const LEDGER_ABI = ${JSON.stringify(ledger.abi)} as const;
export const LEDGER_BYTECODE = "0x${ledger.evm.bytecode.object}" as const;
export const LEDGER_RUNTIME = "0x${ledger.evm.deployedBytecode.object}" as const;
export const SOLC_VERSION = "${solc.version()}";
`;
writeFileSync(join(dir, "artifacts.ts"), out);
console.log(`simulator ${sim.evm.deployedBytecode.object.length / 2} bytes, ledger ${ledger.evm.deployedBytecode.object.length / 2} bytes`);
