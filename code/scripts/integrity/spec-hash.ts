/**
 * Writes lib/integrity/spec-hash.ts: the keccak256 of the paper's Appendix A (the normative
 * specification) as published. Run after every change to the appendix:
 *
 *   npx tsx scripts/integrity/spec-hash.ts <path to the paper's Markdown>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256, toBytes } from "viem";

const source = readFileSync(process.argv[2], "utf8");
const start = source.indexOf("## Appendix A.");
const end = source.indexOf("## Appendix B.");
if (start < 0 || end < start) throw new Error("Appendix A not found");
const text = source.slice(start, end).trim();
const hash = keccak256(toBytes(text));
writeFileSync("lib/integrity/spec-hash.ts", `// Generated by scripts/integrity/spec-hash.ts from the paper's Appendix A. Do not edit.\nexport const SPEC_TEXT_HASH = "${hash}";\n`);
console.log(hash);
